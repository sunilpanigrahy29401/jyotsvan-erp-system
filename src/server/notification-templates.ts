/**
 * Safely renders a template string by replacing {{key}} tokens with values from payload,
 * sanitizing any malicious script/HTML injection.
 */
export function renderTemplate(templateStr: string, payload: Record<string, any>): string {
  if (!templateStr) return '';
  return templateStr.replace(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g, (_, key) => {
    const val = payload[key];
    if (val === undefined || val === null) {
      return '';
    }
    // Sanitize string value to prevent XSS / malicious control characters
    const str = String(val);
    return str
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  });
}
