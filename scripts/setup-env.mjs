#!/usr/bin/env node
// One-command local setup of .env (never committed). Safe to re-run: it will not overwrite an existing .env
// unless you pass --force. Secrets are generated locally; project values are read from the InsForge CLI if you are
// logged in and linked. Nothing here is sent anywhere.
//   npm run setup:env            create .env (generates SESSION_SECRET and ENCRYPTION_SECRET)
//   npm run setup:env -- --force overwrite an existing .env (a backup .env.bak is kept)
import crypto from 'node:crypto';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const force = process.argv.includes('--force');
if (fs.existsSync('.env') && !force) {
  console.log('.env already exists; leaving it untouched (use --force to regenerate, a backup is kept).');
  process.exit(0);
}
if (fs.existsSync('.env')) fs.copyFileSync('.env', '.env.bak');

const rand = (n) => crypto.randomBytes(n).toString('base64url');
const values = {
  NODE_ENV: 'development',
  SESSION_SECRET: rand(48),
  ENCRYPTION_SECRET: rand(48),
  CRM_INGEST_KEY: rand(24),
  COOKIE_SECURE: 'false', // plain-HTTP local development; keep the default (true) in production
  DATABASE_SSL: 'disable', // set DATABASE_SSL_CA instead when pointing at a managed database
  RUN_MIGRATIONS_ON_BOOT: 'false',
  DATABASE_URL: '',
  VITE_INSFORGE_PROJECT_ID: '',
  VITE_INSFORGE_API_URL: '',
  VITE_INSFORGE_ANON_KEY: '',
  GEMINI_API_KEY: '',
};

// Project public values from the linked InsForge project (no secrets).
try {
  const proj = JSON.parse(fs.readFileSync('.insforge/project.json', 'utf8'));
  values.VITE_INSFORGE_API_URL = proj.oss_host || '';
  values.VITE_INSFORGE_PROJECT_ID = proj.appkey || '';
} catch { /* not linked: leave blank */ }

const cli = (args) => {
  try {
    return execFileSync('npx', ['-y', '@insforge/cli', ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], env: { ...process.env, NODE_USE_ENV_PROXY: '1', DO_NOT_TRACK: '1' } });
  } catch { return ''; }
};
if (process.argv.includes('--with-database')) {
  // Prints nothing; only written into the local .env file (mode 600).
  const out = cli(['db', 'connection-string', '--json']);
  try {
    const d = JSON.parse(out);
    values.DATABASE_URL = d.connectionString || d.url || d.connection_string || '';
    if (values.DATABASE_URL) values.DATABASE_SSL = ''; // verify TLS by default against the managed database
  } catch { /* leave blank */ }
}

const lines = [
  '# Generated by `npm run setup:env`. NEVER commit this file (it is git-ignored).',
  ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
  '',
  '# Optional: META_APP_ID, META_APP_SECRET, META_API_VERSION, META_OAUTH_REDIRECT_URI, TRUST_PROXY, PORT, RLS_ENABLED',
  '# See .env.example for every setting.',
  '',
];
fs.writeFileSync('.env', lines.join('\n'), { mode: 0o600 });
console.log('Created .env (mode 600). Generated: SESSION_SECRET, ENCRYPTION_SECRET, CRM_INGEST_KEY.');
if (!values.DATABASE_URL) console.log('DATABASE_URL is empty: run `npm run setup:env -- --force --with-database` after `npx @insforge/cli login`, or paste it yourself.');
if (!values.VITE_INSFORGE_ANON_KEY) console.log('VITE_INSFORGE_ANON_KEY is empty (only needed if you use the InsForge browser SDK).');
if (!values.GEMINI_API_KEY) console.log('GEMINI_API_KEY is empty: AI copilot answers are disabled until set.');
